type Props = {
  name?: string | null
  size?: number
  className?: string
}

export function Icon({ name, size = 24, className }: Props) {
  const Cmp = name ? icons[name as IconName] : undefined
  if (!Cmp) return null
  return <Cmp size={size} strokeWidth={1.5} aria-hidden="true" className={className} />
}
